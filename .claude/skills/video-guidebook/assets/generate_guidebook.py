#!/usr/bin/env python3
"""
Superkind-branded Guidebook PDF generator.

Produces the 2-3 page lead-magnet PDF that gets sent (via DM automation) to
anyone who comments the trigger word under a video generated by the
heygen-video-generator skill. Branding (colors, font, logo, tone) is pulled
from superkind.ai, verified live on 2026-09-23. Credited to Florent Preusser
(the on-camera creator/channel owner) x Superkind (the company these videos
promote).

Usage (called by the skill, not run standalone with hardcoded content):

    from generate_guidebook import build_guidebook
    build_guidebook(content_dict, "/path/to/output.pdf")

See the CONTENT SPEC comment below for the exact shape `content_dict` must have.
"""

import os

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors as rl_colors
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
    HRFlowable, KeepTogether, Flowable,
)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from svglib.svglib import svg2rlg

# ---------------------------------------------------------------------------
# CONTENT SPEC — the dict passed to build_guidebook() must look like this:
#
# {
#   "topic": "Buchhaltung",                       # short topic name
#   "title": "Buchhaltung mit KI automatisieren",  # PDF title / H1
#   "trigger_word": "BELEGE",
#   "intro": "1-3 sentences framing what this guide delivers.",
#   "skills": ["Real Claude Skill or capability, one per line", ...],
#   "connectors": ["Real MCP/Connector needed, one per line", ...],
#   "steps": [
#       {"title": "Schritt 1: ...", "body": "Full-depth explanation, not the teased version."},
#       ...
#   ],
#   "prompts": [
#       {"label": "Prompt 1 — Analyse", "text": "Verbatim prompt text to copy-paste."},
#       ...
#   ],
#   "tips": ["Short troubleshooting/best-practice bullet", ...],
# }
#
# Pull skills/connectors/prompts content from the sibling skill's
# ai-tool-stack-playbook.md for real, verified tool-stack info per topic —
# never invent a tool/product name to sound credible (same rule as the
# script itself).
# ---------------------------------------------------------------------------

HERE = os.path.dirname(os.path.abspath(__file__))
FONT_DIR = os.path.join(HERE, "fonts")
LOGO_PATH = os.path.join(HERE, "superkind-logo.svg")

ACCENT = rl_colors.HexColor("#FF6B35")   # Superkind orange, verified live 2026-09-23
INK = rl_colors.HexColor("#111111")      # Superkind body text color
DARK = rl_colors.HexColor("#0A0A0A")     # Superkind button/CTA-box background
MUTED = rl_colors.HexColor("#6B7280")
CODE_BG = rl_colors.HexColor("#F4F4F5")
RULE = rl_colors.HexColor("#E5E5E5")

CALENDLY_URL = "https://calendly.com/henri-superkind/30min"
SITE_URL = "https://superkind.ai"


def _register_fonts():
    pdfmetrics.registerFont(TTFont("Inter", os.path.join(FONT_DIR, "Inter-Regular.ttf")))
    pdfmetrics.registerFont(TTFont("Inter-Medium", os.path.join(FONT_DIR, "Inter-Medium.ttf")))
    pdfmetrics.registerFont(TTFont("Inter-SemiBold", os.path.join(FONT_DIR, "Inter-SemiBold.ttf")))
    pdfmetrics.registerFont(TTFont("Inter-Bold", os.path.join(FONT_DIR, "Inter-Bold.ttf")))


def _styles():
    return {
        "kicker": ParagraphStyle(
            "kicker", fontName="Inter-SemiBold", fontSize=9, leading=11,
            textColor=ACCENT, spaceAfter=4, tracking=0.5,
        ),
        "h1": ParagraphStyle(
            "h1", fontName="Inter-Bold", fontSize=24, leading=28,
            textColor=INK, spaceAfter=10,
        ),
        "intro": ParagraphStyle(
            "intro", fontName="Inter", fontSize=11, leading=16,
            textColor=INK, spaceAfter=14,
        ),
        "h2": ParagraphStyle(
            "h2", fontName="Inter-Bold", fontSize=14, leading=18,
            textColor=INK, spaceBefore=16, spaceAfter=8,
        ),
        "body": ParagraphStyle(
            "body", fontName="Inter", fontSize=10.2, leading=14.5,
            textColor=INK, spaceAfter=6, alignment=TA_LEFT,
        ),
        "step_title": ParagraphStyle(
            "step_title", fontName="Inter-SemiBold", fontSize=11, leading=14,
            textColor=INK, spaceAfter=2,
        ),
        "bullet": ParagraphStyle(
            "bullet", fontName="Inter", fontSize=10.2, leading=14.5,
            textColor=INK, leftIndent=12, spaceAfter=4,
        ),
        "prompt_label": ParagraphStyle(
            "prompt_label", fontName="Inter-SemiBold", fontSize=9.5, leading=12,
            textColor=ACCENT, spaceAfter=3,
        ),
        "prompt_text": ParagraphStyle(
            "prompt_text", fontName="Inter", fontSize=9.3, leading=13.5,
            textColor=INK, fontStyle="normal",
        ),
        "footer": ParagraphStyle(
            "footer", fontName="Inter", fontSize=8, leading=11,
            textColor=MUTED,
        ),
        "cta_h": ParagraphStyle(
            "cta_h", fontName="Inter-Bold", fontSize=13, leading=16,
            textColor=rl_colors.white, spaceAfter=4,
        ),
        "cta_body": ParagraphStyle(
            "cta_body", fontName="Inter", fontSize=9.5, leading=13.5,
            textColor=rl_colors.HexColor("#D4D4D4"),
        ),
        "cta_link": ParagraphStyle(
            "cta_link", fontName="Inter-SemiBold", fontSize=9.5, leading=13.5,
            textColor=ACCENT,
        ),
    }


def _logo_flowable(height_mm=6):
    drawing = svg2rlg(LOGO_PATH)
    scale = (height_mm * mm) / drawing.height
    drawing.width *= scale
    drawing.height *= scale
    drawing.scale(scale, scale)
    # Recolor the monochrome mark from source black to Superkind ink, since
    # this PDF uses a light page background (the live site's white logo is
    # only for its dark hero section) — see contents[:] walk below.
    def _recolor(node):
        if hasattr(node, "contents"):
            for c in node.contents:
                _recolor(c)
        if hasattr(node, "fillColor") and node.fillColor is not None:
            node.fillColor = INK
    _recolor(drawing)
    return drawing


def _header_flowable(styles):
    logo = _logo_flowable()
    wordmark = Paragraph(
        '<font name="Inter-Bold" size="13" color="#111111">Superkind</font>',
        styles["body"],
    )
    credit = Paragraph(
        '<font color="#6B7280">Ein Guide von </font>'
        '<font name="Inter-SemiBold" color="#111111">Florent Preusser</font>'
        '<font color="#6B7280"> &times; Superkind</font>',
        styles["footer"],
    )
    t = Table(
        [[logo, wordmark, "", credit]],
        colWidths=[8 * mm, 28 * mm, None, 90 * mm],
    )
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (3, 0), (3, 0), "RIGHT"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return t


def _prompt_box(label, text, styles):
    inner = Table(
        [[Paragraph(label, styles["prompt_label"])],
         [Paragraph(text.replace("\n", "<br/>"), styles["prompt_text"])]],
        colWidths=[164 * mm],
    )
    inner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CODE_BG),
        ("BOX", (0, 0), (-1, -1), 0.75, RULE),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (0, 0), 8),
        ("BOTTOMPADDING", (0, 0), (0, 0), 2),
        ("TOPPADDING", (0, 1), (0, 1), 2),
        ("BOTTOMPADDING", (0, 1), (0, 1), 8),
    ]))
    return KeepTogether([inner, Spacer(1, 8)])


def _cta_box(content, styles):
    trigger = content.get("trigger_word", "")
    rows = [
        [Paragraph("Willst du das nicht selbst aufsetzen?", styles["cta_h"])],
        [Paragraph(
            f"Superkind baut AI-Mitarbeiter wie diesen direkt in eure "
            f"bestehenden Systeme &mdash; live in wenigen Wochen, ohne "
            f"sechsstellige Implementierungsrisiken. Buch dir ein kurzes, "
            f"unverbindliches Gespr&auml;ch:", styles["cta_body"]
        )],
        [Paragraph(f'<link href="{CALENDLY_URL}">{CALENDLY_URL}</link>', styles["cta_link"])],
        [Spacer(1, 4)],
        [Paragraph(
            f'Und folg <font name="Inter-SemiBold" color="#FFFFFF">Florent Preusser</font> '
            f'f&uuml;r mehr Guides wie diesen &mdash; n&auml;chstes Mal '
            f'einfach <font name="Inter-SemiBold" color="#FF6B35">{trigger}</font> kommentieren.',
            styles["cta_body"]
        )],
    ]
    box = Table(rows, colWidths=[164 * mm])
    box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), DARK),
        ("LEFTPADDING", (0, 0), (-1, -1), 16),
        ("RIGHTPADDING", (0, 0), (-1, -1), 16),
        ("TOPPADDING", (0, 0), (0, 0), 14),
        ("BOTTOMPADDING", (0, -1), (0, -1), 14),
        ("TOPPADDING", (0, 1), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 1), (-1, -2), 2),
    ]))
    return box


def build_guidebook(content: dict, output_path: str):
    _register_fonts()
    styles = _styles()

    doc = SimpleDocTemplate(
        output_path, pagesize=A4,
        leftMargin=23 * mm, rightMargin=23 * mm,
        topMargin=18 * mm, bottomMargin=18 * mm,
        title=content.get("title", content.get("topic", "Guide")),
        author="Florent Preusser x Superkind",
    )

    story = []

    story.append(_header_flowable(styles))
    story.append(Spacer(1, 18))
    story.append(HRFlowable(width="100%", thickness=0.75, color=RULE, spaceAfter=14))

    story.append(Paragraph("GUIDEBOOK", styles["kicker"]))
    story.append(Paragraph(content["title"], styles["h1"]))
    story.append(Paragraph(content["intro"], styles["intro"]))

    # "Was du brauchst" — Skills + Connectors
    story.append(Paragraph("Was du brauchst", styles["h2"]))
    if content.get("skills"):
        story.append(Paragraph(
            '<font name="Inter-SemiBold">Claude Skills</font>', styles["body"]
        ))
        for s in content["skills"]:
            story.append(Paragraph(f"&bull;&nbsp; {s}", styles["bullet"]))
        story.append(Spacer(1, 6))
    if content.get("connectors"):
        story.append(Paragraph(
            '<font name="Inter-SemiBold">Connectors / MCPs</font>', styles["body"]
        ))
        for c in content["connectors"]:
            story.append(Paragraph(f"&bull;&nbsp; {c}", styles["bullet"]))

    # Steps
    story.append(Paragraph("Schritt f&uuml;r Schritt", styles["h2"]))
    for i, step in enumerate(content.get("steps", []), start=1):
        story.append(KeepTogether([
            Paragraph(step["title"], styles["step_title"]),
            Paragraph(step["body"], styles["body"]),
        ]))

    # Prompts
    if content.get("prompts"):
        story.append(Paragraph("Die Prompts zum Copy-Paste", styles["h2"]))
        for p in content["prompts"]:
            story.append(_prompt_box(p["label"], p["text"], styles))

    # Tips
    if content.get("tips"):
        story.append(Paragraph("Tipps &amp; Stolperfallen", styles["h2"]))
        for tip in content["tips"]:
            story.append(Paragraph(f"&bull;&nbsp; {tip}", styles["bullet"]))

    story.append(Spacer(1, 16))
    # KeepTogether so the dark CTA box never splits across a page break —
    # without this, longer guides (more steps/prompts) can push the box
    # across two pages and its background color renders as two disconnected
    # fragments instead of one solid box.
    story.append(KeepTogether([_cta_box(content, styles)]))

    doc.build(story)
    return output_path


def _cli():
    import argparse
    import json

    parser = argparse.ArgumentParser(description="Build a Superkind-branded Guidebook PDF.")
    parser.add_argument("--json", help="Path to a JSON file matching the CONTENT SPEC above.")
    parser.add_argument("--out", help="Output PDF path.", required=False)
    args = parser.parse_args()

    if args.json:
        with open(args.json, "r", encoding="utf-8") as f:
            content = json.load(f)
        out_path = args.out or os.path.join(
            os.getcwd(), f"{content.get('topic', 'guide').lower()}-guidebook.pdf"
        )
        out = build_guidebook(content, out_path)
        print("Built:", out)
    else:
        # Minimal smoke test with placeholder content — no --json given.
        demo = {
            "topic": "Demo",
            "title": "Demo-Thema mit KI automatisieren",
            "trigger_word": "DEMO",
            "intro": "Das ist ein Testlauf des Guidebook-Templates, kein echter Inhalt.",
            "skills": ["Beispiel-Skill A", "Beispiel-Skill B"],
            "connectors": ["Beispiel-Connector"],
            "steps": [
                {"title": "Schritt 1: Test", "body": "Beispieltext für den ersten Schritt."},
            ],
            "prompts": [
                {"label": "Prompt 1 — Test", "text": "Das ist ein Beispiel-Prompt zum Testen des Layouts."},
            ],
            "tips": ["Beispiel-Tipp."],
        }
        out = build_guidebook(demo, args.out or os.path.join(HERE, "_smoketest.pdf"))
        print("Built (demo content):", out)


if __name__ == "__main__":
    _cli()
